/**
 * Единая точка чтения env-конфига. Значения ограничений (email/secret/token) — из openapi,
 * держим здесь для тест-сверки и валидации форм.
 */

export type TokenMode = 'cookie' | 'body';

export const config = {
  authApiBaseUrl: import.meta.env.VITE_AUTH_API_BASE_URL ?? '/api/auth',
  /** realm-константа деплоя; обязателен на signin/signup/check-login — дефолта бэкенд не
   *  подставляет, без realm запрос падает с 400. */
  realm: import.meta.env.VITE_AUTH_REALM ?? 'print-shop/standard',
  tokenMode: (import.meta.env.VITE_TOKEN_MODE ?? 'cookie') as TokenMode,
  /** Не задан — в деве включено, в проде нет; '0' явно выключает (работа против живого бэка).
   *  Потребитель (bootstrap в main.tsx) гейтит подъём msw ещё и по import.meta.env.DEV, поэтому
   *  в сборке с mode=production флаг не поднимет моки ни при каком значении. */
  enableMocks:
    import.meta.env.VITE_ENABLE_MOCKS !== undefined
      ? import.meta.env.VITE_ENABLE_MOCKS === '1'
      : import.meta.env.DEV,
} as const;

/**
 * Границы полей, которые пользователь вводит руками, — из openapi.yaml, сверяются тестом
 * constants.test.ts. Форма отсекает по ним заведомо невалидное до запроса.
 *
 * Всё остальное сюда не попадает: значения из справочников и селектов набрать нельзя, константы
 * деплоя приходят из env, а данные из ответов бэка проверять незачем.
 */
export const limits = {
  userLogin: { min: 7, max: 64 },
  secret: { min: 4, max: 32 },
  /** Пароль как второй фактор: границы формы его установки — единственного места, где вводят
   *  именно пароль и ничего кроме. Звенья подтверждения меряются границами secret, включая
   *  парольное: одно поле обслуживает несколько форматов разом — вместо пароля там принимается
   *  аварийный код, — и сузить его до пароля нельзя. */
  password: { min: 8, max: 32 },
  /** Код из TOTP-приложения: ровно 6 цифр. */
  totpCode: { min: 6, max: 6 },
  /** Код подтверждения из сообщения: не длиннее 6 цифр. Нижняя граница — контрактная, от поля
   *  secret; верхнюю знает продукт — контракт объявил 4..32 на все форматы разом и шестёрку ничем
   *  не держит. Поле применяет её жёстко: лишние цифры отбрасываются при вводе, поэтому код другой
   *  длины стал бы невводимым молча — ни constants.test.ts, ни спека такого расхождения не покажут,
   *  его придётся править здесь. */
  confirmCode: { min: 4, max: 6 },
} as const;

/**
 * За сколько секунд до истечения access делаем проактивный refresh. Сам срок жизни не хардкодим:
 * он приходит в expires_in каждого ответа и заметно разный по режимам деплоя (минуты у jwt,
 * десятки минут у непрозрачного access) — здесь только запас на дорогу до сервера.
 */
export const PROACTIVE_REFRESH_SKEW_SEC = 30;
