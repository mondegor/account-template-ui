import { getCorrelationId } from './correlationId';

/**
 * Заголовки, которые фронт добавляет во ВСЕ запросы.
 *
 * Тут только `X-Correlation-Id`: `Accept-Language` намеренно НЕ ставим. Этот заголовок — сигнал
 * окружения («язык моего браузера»), и браузер добавляет его сам; подменив его выбранным языком
 * интерфейса, мы бы испортили ровно те два места, где сервер его и читает, — регистрацию
 * и сохранение настроек в режиме «Авто». Выбранный язык уезжает отдельно, query-параметром
 * `?lang` (см. httpClient), и по приоритету спеки он всё равно старше заголовка.
 *
 * Пояса тут тоже нет, но по другой причине: у `X-Accept-Time-Zone` браузерного аналога нет,
 * собирать его приходится самим — и только там, где сервер до него дойдёт. Это гостевые запросы
 * (ставит интерсептор authClient) и сохранение настроек в режиме «Авто» (ставит authApi).
 */
export function commonHeaders(): Record<string, string> {
  return {
    'X-Correlation-Id': getCorrelationId(),
  };
}
