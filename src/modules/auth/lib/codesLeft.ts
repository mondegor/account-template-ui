/**
 * Ступень остатка аварийных кодов — одна на всё приложение. Показывают остаток двое, полоса защиты
 * на профиле и карточка настроек, и говорят они разное: полоса зовёт перевыпустить, карточка держит
 * призыв отдельной ссылкой. Разойтись им можно в словах, но не в том, с какого остатка тревожиться.
 *
 * Ступень считается только из самого остатка: защита при кончающихся кодах цела, кончается запасной
 * выход, — поэтому на тон второго фактора она не влияет.
 */

/** Остаток, на котором предупреждение становится красным: «запасного выхода почти нет». */
const CODES_ALARM = 1;
/** Остаток, ниже которого предупреждение вообще появляется; выше — запаса хватает. */
const CODES_LOW = 4;

export type CodesLevel = 'empty' | 'last' | 'low' | 'enough';

export function codesLeftLevel(left: number): CodesLevel {
  if (left === 0) return 'empty';
  if (left <= CODES_ALARM) return 'last';
  return left < CODES_LOW ? 'low' : 'enough';
}

/**
 * Тон ступени. `none` — не «нет цвета», а «поводов тревожиться нет»: строка идёт обычным текстом.
 */
export function codesLeftTone(level: CodesLevel): 'error' | 'warning' | 'none' {
  if (level === 'empty' || level === 'last') return 'error';
  return level === 'low' ? 'warning' : 'none';
}
