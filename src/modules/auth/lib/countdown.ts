/** Отсчёты экрана подтверждения: срок жизни операции и время до повторной отправки. */

/**
 * Нулём минуты дополняются только там, где отсчёт переваливает за десять минут, — у срока жизни
 * операции: иначе на переходе через десять ширина числа меняется и подпись дёргается. Отсчёты
 * повторной отправки минуты не достигают вовсе, и ведущий ноль был бы у них просто шумом.
 *
 * Срок от часа и больше идёт с часами (`71:59:59`): подтверждение нового адреса при смене емаила
 * живёт порядка трёх суток, и тысячи минут читать некому. Минуты при часах дополняются всегда.
 */
export function mmss(total: number, padMinutes = false): string {
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = String(total % 60).padStart(2, '0');
  if (h > 0) return `${h}:${String(m).padStart(2, '0')}:${s}`;
  const mm = padMinutes ? String(m).padStart(2, '0') : String(m);
  return `${mm}:${s}`;
}
