import { limits } from '@config';

/**
 * Форматы секретов, которые человек набирает руками, и всё, чем они друг от друга отличаются:
 * границы, обрезка краёв, автозаполнение и то, чем их набирают.
 *
 * Каждому формату его собственные границы даёт явный выбор режима. Без него мерить было бы нечем:
 * звено второго фактора принимает и пароль, и аварийный код, а отличить их по вводу нельзя —
 * пароль может содержать дефис и выглядеть как код.
 */

/** Код из сообщения и код из приложения разведены: у них разные границы и разная подпись. */
export type SecretMode = 'CODE' | 'TOTP' | 'PASSWORD' | 'RECOVERY';

/**
 * Форматы второго фактора, вместо которых спека разрешает предъявить аварийный код. Кода из
 * сообщения среди них нет: подменять его нечем, и значка у него не бывает.
 */
export type SwapMode = 'PASSWORD' | 'TOTP';

/**
 * Допускает ли формат звена подмену аварийным кодом. Спрашивают об этом двое — переключатель у
 * подписи поля и примечание в подвале, показывающее на него, — и ответ у них обязан быть один:
 * разойдись они, примечание звало бы к значку, которого на экране нет.
 */
export function isSwapMode(mode: SecretMode): mode is SwapMode {
  return mode === 'PASSWORD' || mode === 'TOTP';
}

export interface SecretFormat {
  label: string;
  /** Чем набирают: ряд клеток, скрытое поле с глазом, открытое моноширинное поле. */
  kind: 'digits' | 'password' | 'mono';
  /**
   * Нижняя граница включает кнопку, верхняя ограничивает ввод: заведомо короткое значение сервер
   * всё равно отклонит, а попытка на звене сгорит — их всего три.
   */
  length: { min: number; max: number };
  /**
   * Обрезать ли пробелы по краям перед отправкой. Обрезают все форматы, кроме пароля: в них пробел
   * не входит, а приезжает вставкой — из списка аварийных кодов или из сообщения. Уйди такой край
   * на сервер, тот ответил бы «неверный код» и списал попытку за то, чего человек не набирал.
   *
   * У пароля ограничений на символы нет вовсе, и краевой пробел в нём — часть секрета: обрежь его,
   * и попытки сгорели бы на значении, которого никто не вводил.
   */
  trim: boolean;
  autoComplete: string;
}

export const SECRET_FORMAT: Record<SecretMode, SecretFormat> = {
  CODE: {
    label: 'auth.field.code',
    kind: 'digits',
    length: limits.confirmCode,
    trim: true,
    autoComplete: 'one-time-code',
  },
  TOTP: {
    label: 'auth.field.totpCode',
    kind: 'digits',
    length: limits.totpCode,
    trim: true,
    autoComplete: 'off',
  },
  PASSWORD: {
    label: 'auth.field.password',
    kind: 'password',
    length: limits.password,
    trim: false,
    // Менеджер паролей — единственный способ вообще иметь длинный пароль, и в парольном режиме
    // поле однозначно парольное: подменить его аварийным кодом можно только явным переключением,
    // а там автозаполнения нет. Выключи его здесь — и это подталкивало бы к коротким паролям.
    autoComplete: 'current-password',
  },
  RECOVERY: {
    label: 'auth.field.recoveryCode',
    kind: 'mono',
    length: limits.recoveryCode,
    trim: true,
    // Код одноразовый, сохранять его незачем.
    autoComplete: 'off',
  },
};

/** Значение, каким оно уйдёт на сервер: по нему же меряется и включение кнопки. */
export function secretValue(mode: SecretMode, value: string): string {
  return SECRET_FORMAT[mode].trim ? value.trim() : value;
}
