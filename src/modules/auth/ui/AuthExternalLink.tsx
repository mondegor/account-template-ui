import { Link } from '@mui/material';

/**
 * Ссылка на документ снаружи приложения (условия использования). Якорь, а не кнопка роутера, как
 * `AuthNavLink`: адрес приходит из конфига деплоя и маршрутом фронта не является.
 *
 * Новая вкладка — чтобы набранное в форме осталось на месте; `rel` при этом обязателен: он
 * отбирает у открытой страницы доступ к `window.opener` и убирает наш адрес из её реферера.
 *
 * Размер шрифта не задаём: якорь наследует его от строки, внутри которой стоит, — и в сноске
 * подвала ссылка получается ровно такой же мелкой, как её текст.
 */
export function AuthExternalLink({ href, children }: { href: string; children: string }) {
  return (
    <Link href={href} target="_blank" rel="noopener noreferrer">
      {children}
    </Link>
  );
}
