import { Box, Typography } from '@mui/material';

/**
 * Признак «это ваш текущий кабинет / ваша текущая сессия»: точка и слово под названием карточки.
 * Один компонент на профиль и на сессии — приём общий, и разъезжаться ему нельзя.
 *
 * Работает подпись, а не геометрия: рамкой карточку выделять нечем — тем же синим рядом говорит
 * полоса защиты, и два одинаково громких сигнала о разном спорили бы друг с другом. Зелёный здесь
 * достаётся только точке и самому слову: соседние элементы им красить нельзя, на этом же экране
 * он означает «максимальная защита».
 *
 * Метка живёт внутри чужой строки (на сессиях за ней через разделитель идёт название приложения),
 * поэтому и точка, и слово остаются обычным текстом в потоке: у флекс-контейнера базовую линию
 * задал бы первый элемент — пустая точка, и подпись встала бы ниже соседей по строке.
 */
export function CurrentMark({ label }: { label: string }) {
  return (
    <Typography variant="caption" component="span" sx={{ color: 'success.main', fontWeight: 600 }}>
      <Box
        component="span"
        sx={{
          display: 'inline-block',
          width: 6,
          height: 6,
          mr: 0.75,
          borderRadius: '50%',
          bgcolor: 'success.main',
          verticalAlign: 'middle',
        }}
      />
      {label}
    </Typography>
  );
}
