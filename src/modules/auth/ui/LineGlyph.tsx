import type { ReactNode } from 'react';
import { Box } from '@mui/material';
import { textLine } from './textLine';

/**
 * Коробка глифа в строке со знаком: остаток аварийных кодов, примечание к карточке,
 * предупреждение в полоске защиты. Знак у всех троих стоит при тексте `body2`, и посадка у него
 * одна — разъехавшись, они читались бы как знаки разной важности.
 *
 * Коробка ростом ровно в строку текста: знак встаёт по центру первой строки, а не по верху всего
 * блока. `alignSelf` уводит коробку из-под выравнивания ряда — метит знак первую строку, и на
 * переносе текста центрирование по ряду увело бы его вниз. Высота берётся из той же типографики,
 * которой набрана строка, чтобы не расходиться с ней.
 *
 * Оптическая поправка: буквы стоят в своей строке выше её геометрического центра, и знак,
 * выровненный по коробке, читается приподнятым. Поправка идёт смещением, а не отступом: Stack со
 * spacing обнуляет margin у детей правилом более высокой специфичности, чем класс sx, — отступ
 * отсюда до элемента не дошёл бы.
 *
 * Цвет задаётся путём в палитре, не литералом; без него знак идёт цветом окружающего текста.
 */
export function LineGlyph({
  color = 'inherit',
  children,
}: {
  color?: string;
  children: ReactNode;
}) {
  return (
    <Box
      sx={{
        display: 'flex',
        alignItems: 'center',
        alignSelf: 'flex-start',
        flexShrink: 0,
        height: textLine('body2'),
        position: 'relative',
        top: '1px',
        color,
      }}
    >
      {children}
    </Box>
  );
}
