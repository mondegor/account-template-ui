import type { Theme } from '@mui/material';

/**
 * Высота строки названия карточки. Ею меряются соседи названия — глиф-якорь слева и действие
 * справа: оба относятся к названию и встают по центру именно его строки, а не по центру всей
 * шапки, которую подпись под названием разгоняет вниз.
 *
 * Приём общий для заголовков профиля (`subtitle2`) и карточки сессии (`subtitle1`), поэтому и
 * формула одна: разъехавшись, они дали бы разную посадку глифа на соседних экранах.
 */
export const titleLine = (variant: 'subtitle1' | 'subtitle2') => (theme: Theme) =>
  `calc(${theme.typography[variant].fontSize} * ${theme.typography[variant].lineHeight})`;
