import { i18next } from '@core/i18n';

/**
 * Подпись из i18n на текущем языке теста.
 *
 * Фразы интерфейса в тестах руками не пишем: литерал дублирует файл переводов, поэтому падает от
 * правки формулировки — то есть проверяет её, а не то, что на экране нужный ключ. Ключ, наоборот,
 * называет предмет проверки и переживает редактуру текста.
 *
 * Не относится к значениям, которые интерфейс не переводит: имена устройств, серверные detail,
 * тексты, которые компонент получает пропами. Они пишутся литералом — и литералом английским,
 * как и всё, что в тестах придумано самим тестом.
 */
export function tr(key: string, opts?: Record<string, unknown>): string {
  return i18next.t(key, opts ?? {});
}
