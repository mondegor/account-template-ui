import type { Theme } from '@mui/material';

/**
 * Зазор под блоком поля — тем, что идёт следом: соседним полем, плашкой, кнопкой.
 *
 *  - `quiet` — под полем ничего, зазор полный;
 *  - `message` — под полем строка сообщения; полный зазор под мелким текстом читается как дырка,
 *    поэтому он вдвое меньше;
 *  - `flush` — строку под блоком рисует кто-то снаружи. Блок кончается вплотную, а зазор за
 *    строкой держит тот, кто её рисует: своя строка и чужая обязаны стоять одинаково.
 *
 * Зазор едет плавно, вместе с раскрытием самой строки (`UiFieldMessage`) — иначе то, что ниже,
 * дёргалось бы на её появлении.
 */
export function uiFieldBlockSx(gap: 'quiet' | 'message' | 'flush') {
  return {
    mb: { quiet: 2, message: 1, flush: 0 }[gap],
    transition: (theme: Theme) => theme.transitions.create('margin-bottom'),
  };
}
